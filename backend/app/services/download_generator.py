import os
import tempfile
from typing import List
from app.models.schemas import EpisodeDownloadInfo, VideoSource

class DownloadFileGenerator:
    """Generate batch download files for various download managers."""
    
    @staticmethod
    def generate_idm_ef2(episodes: List[EpisodeDownloadInfo], output_dir: str = None) -> tuple[str, str]:
        """
        Generate IDM batch download file (.ef2 format).
        IDM uses a proprietary format, but we can generate a text file with URLs
        that can be imported via "Add Batch" -> "From text file".
        Actually, IDM's .ef2 is binary. The common approach is to generate a .txt
        with one URL per line and use IDM's "Add Batch from clipboard/file".
        """
        lines = []
        lines.append("# IDM Batch Download List")
        lines.append(f"# Generated by Wcoflix Downloader")
        lines.append(f"# Total episodes: {len(episodes)}")
        lines.append("")
        
        for ep_info in episodes:
            if ep_info.error:
                lines.append(f"# ERROR: {ep_info.episode.title} - {ep_info.error}")
                continue
            
            ep = ep_info.episode
            lines.append(f"# {ep.title} (S{ep.season}E{ep.episode}) - {ep.language.value.upper()}")
            
            # Use the best quality source (prefer 1080p, then 720p, then first available)
            best_source = DownloadFileGenerator._select_best_source(ep_info.video_sources)
            if best_source:
                lines.append(str(best_source.url))
            else:
                lines.append(f"# NO VIDEO SOURCE FOUND")
            lines.append("")
        
        content = "\n".join(lines)
        filename = "wcoflix_batch_download_idm.txt"
        
        if output_dir:
            filepath = os.path.join(output_dir, filename)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            return filepath, content
        
        return filename, content

    @staticmethod
    def generate_ab_downloader(episodes: List[EpisodeDownloadInfo], output_dir: str = None) -> tuple[str, str]:
        """
        Generate AB Downloader batch file.
        AB Downloader accepts simple text files with URLs, one per line.
        Can also use .lst format with name|url pairs.
        """
        lines = []
        lines.append("[AB Downloader Batch List]")
        lines.append(f"Count={len(episodes)}")
        lines.append("")
        
        for i, ep_info in enumerate(episodes, 1):
            if ep_info.error:
                lines.append(f"{i}=ERROR: {ep_info.episode.title} - {ep_info.error}||")
                continue
            
            ep = ep_info.episode
            best_source = DownloadFileGenerator._select_best_source(ep_info.video_sources)
            if best_source:
                # Format: Name|URL|Referer|Cookie|PostData|UserAgent
                name = f"{ep.title}.mp4"
                lines.append(f"{i}={name}|{best_source.url}||||")
            else:
                lines.append(f"{i}=ERROR: No video source||")
        
        content = "\n".join(lines)
        filename = "wcoflix_batch_download_abd.lst"
        
        if output_dir:
            filepath = os.path.join(output_dir, filename)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            return filepath, content
        
        return filename, content

    @staticmethod
    def generate_aria2(episodes: List[EpisodeDownloadInfo], output_dir: str = None) -> tuple[str, str]:
        """Generate aria2 input file format."""
        lines = []
        
        for ep_info in episodes:
            if ep_info.error:
                continue
            
            ep = ep_info.episode
            best_source = DownloadFileGenerator._select_best_source(ep_info.video_sources)
            if best_source:
                lines.append(str(best_source.url))
                lines.append(f"  out={ep.title}.mp4")
                lines.append(f"  header=User-Agent: Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36")
                lines.append(f"  header=Referer: https://www.wcoflix.tv/")
        
        content = "\n".join(lines)
        filename = "wcoflix_batch_download_aria2.txt"
        
        if output_dir:
            filepath = os.path.join(output_dir, filename)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            return filepath, content
        
        return filename, content

    @staticmethod
    def generate_simple_txt(episodes: List[EpisodeDownloadInfo], output_dir: str = None) -> tuple[str, str]:
        """Generate simple text file with one URL per line."""
        lines = []
        
        for ep_info in episodes:
            if ep_info.error:
                lines.append(f"# ERROR: {ep_info.episode.title} - {ep_info.error}")
                continue
            
            best_source = DownloadFileGenerator._select_best_source(ep_info.video_sources)
            if best_source:
                lines.append(str(best_source.url))
        
        content = "\n".join(lines)
        filename = "wcoflix_batch_download.txt"
        
        if output_dir:
            filepath = os.path.join(output_dir, filename)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            return filepath, content
        
        return filename, content

    @staticmethod
    def generate_m3u_playlist(episodes: List[EpisodeDownloadInfo], output_dir: str = None) -> tuple[str, str]:
        """Generate M3U playlist for media players."""
        lines = ["#EXTM3U"]
        
        for ep_info in episodes:
            if ep_info.error:
                continue
            
            ep = ep_info.episode
            best_source = DownloadFileGenerator._select_best_source(ep_info.video_sources)
            if best_source:
                lines.append(f"#EXTINF:-1,{ep.title}")
                lines.append(str(best_source.url))
        
        content = "\n".join(lines)
        filename = "wcoflix_playlist.m3u"
        
        if output_dir:
            filepath = os.path.join(output_dir, filename)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            return filepath, content
        
        return filename, content

    @staticmethod
    def _select_best_source(sources: List[VideoSource]) -> VideoSource | None:
        """Select the best quality source from available sources."""
        if not sources:
            return None
        
        # Priority: 1080p > 720p > 480p > Auto > direct > m3u8 > embed
        quality_order = {'1080p': 0, '720p': 1, '480p': 2, 'Auto': 3}
        type_order = {'direct': 0, 'm3u8': 1, 'embed': 2}
        
        def sort_key(s):
            return (quality_order.get(s.quality, 99), type_order.get(s.type, 99))
        
        return min(sources, key=sort_key)

    @staticmethod
    def generate_all_formats(episodes: List[EpisodeDownloadInfo], output_dir: str) -> dict:
        """Generate all download formats and return file paths."""
        results = {}
        
        # Create output directory
        os.makedirs(output_dir, exist_ok=True)
        
        # IDM format
        path, content = DownloadFileGenerator.generate_idm_ef2(episodes, output_dir)
        results['idm'] = {'path': path, 'filename': os.path.basename(path), 'content': content}
        
        # AB Downloader format
        path, content = DownloadFileGenerator.generate_ab_downloader(episodes, output_dir)
        results['ab_downloader'] = {'path': path, 'filename': os.path.basename(path), 'content': content}
        
        # Aria2 format
        path, content = DownloadFileGenerator.generate_aria2(episodes, output_dir)
        results['aria2'] = {'path': path, 'filename': os.path.basename(path), 'content': content}
        
        # Simple txt
        path, content = DownloadFileGenerator.generate_simple_txt(episodes, output_dir)
        results['txt'] = {'path': path, 'filename': os.path.basename(path), 'content': content}
        
        # M3U playlist
        path, content = DownloadFileGenerator.generate_m3u_playlist(episodes, output_dir)
        results['m3u'] = {'path': path, 'filename': os.path.basename(path), 'content': content}
        
        return results